export function foldCountryQuery(value: string): string {
  return value
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()
    .replace(/\s+/g, ' ')
}

export function canonicalCountry(value: string): string | null {
  const folded = foldCountryQuery(value)
  if (!folded) return null
  for (const country of countries) {
    if (foldCountryQuery(country.name) === folded) return country.name
    if (country.aliases?.some(alias => foldCountryQuery(alias) === folded)) return country.name
  }
  return null
}

export function filterCountries(query: string): readonly CountryOption[] {
  const folded = foldCountryQuery(query)
  if (!folded) return countries
  return countries.filter(country => {
    if (foldCountryQuery(country.name).includes(folded)) return true
    return country.aliases?.some(alias => foldCountryQuery(alias).includes(folded)) ?? false
  })
}
